// The tables as the CPU side hands them over.
inline Dsp::Tables DspTables()
{
    Dsp::Tables tables;
    for (std::size_t i = 0; i < kResampleFilter.size(); i++)
    {
        tables.resample[i] = static_cast<int16_t>(kResampleFilter[i]);
    }

    for (std::size_t i = 0; i < kOscillatorTables.size(); i++)
    {
        tables.resample[Dsp::kOscillatorTables + i] = static_cast<int16_t>(kOscillatorTables[i]);
    }

    for (std::size_t i = 0; i < kAutoMixerSine.size(); i++)
    {
        tables.resample[Dsp::kAutoMixerSine + i] = static_cast<int16_t>(kAutoMixerSine[i]);
    }

    for (std::size_t i = 0; i < kAfcCoefficients.size(); i++)
    {
        tables.adpcm[i] = static_cast<int16_t>(kAfcCoefficients[i]);
    }

    return tables;
}

